import {
  Activity,
  Banknote,
  Bell,
  Briefcase,
  Calendar,
  ChartArea,
  ChartColumn,
  ChartLine,
  ChartPie,
  Clock,
  Coins,
  Compass,
  Crosshair,
  Eye,
  Flame,
  Gauge,
  Globe,
  Landmark,
  Layers,
  LayoutDashboard,
  LayoutGrid,
  List,
  type LucideIcon,
  Percent,
  PiggyBank,
  Radar,
  Receipt,
  Scale,
  Shield,
  Sparkles,
  Table,
  Target,
  TrendingDown,
  TrendingUp,
  Wallet,
  Zap,
} from 'lucide-react'

/**
 * Curated lucide icons a view may name in its header (kept small so we don't
 * bundle the whole icon set). Unknown names fall back to LayoutDashboard.
 */
const ICONS: Record<string, LucideIcon> = {
  activity: Activity,
  banknote: Banknote,
  bell: Bell,
  briefcase: Briefcase,
  calendar: Calendar,
  'chart-area': ChartArea,
  'chart-column': ChartColumn,
  'bar-chart': ChartColumn,
  'chart-line': ChartLine,
  'line-chart': ChartLine,
  'chart-pie': ChartPie,
  'pie-chart': ChartPie,
  clock: Clock,
  coins: Coins,
  compass: Compass,
  crosshair: Crosshair,
  eye: Eye,
  flame: Flame,
  gauge: Gauge,
  globe: Globe,
  landmark: Landmark,
  layers: Layers,
  'layout-dashboard': LayoutDashboard,
  'layout-grid': LayoutGrid,
  list: List,
  percent: Percent,
  'piggy-bank': PiggyBank,
  radar: Radar,
  receipt: Receipt,
  scale: Scale,
  shield: Shield,
  sparkles: Sparkles,
  table: Table,
  target: Target,
  'trending-down': TrendingDown,
  'trending-up': TrendingUp,
  wallet: Wallet,
  zap: Zap,
}

export function viewIcon(name: string | null | undefined): LucideIcon {
  return (name && ICONS[name]) || LayoutDashboard
}
